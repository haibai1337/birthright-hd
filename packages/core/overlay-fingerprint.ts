/** JSON canonical form v1: sorted object keys, ordered arrays, JSON scalar encoding.
 * Deliberately rejects values JSON would silently discard or coerce. */
export function canonicalOverlayJSON(value: unknown): string {
  if (value === null || typeof value === 'string' || typeof value === 'boolean')
    return JSON.stringify(value);
  if (typeof value === 'number' && Number.isFinite(value)) return JSON.stringify(value);
  if (Array.isArray(value)) return `[${Array.from(value, canonicalOverlayJSON).join(',')}]`;
  if (typeof value === 'object' && Object.getPrototypeOf(value) === Object.prototype)
    return `{${Object.keys(value)
      .sort()
      .map(
        (k) =>
          `${JSON.stringify(k)}:${canonicalOverlayJSON((value as Record<string, unknown>)[k])}`,
      )
      .join(',')}}`;
  throw new Error('Overlay content must be plain, finite JSON');
}


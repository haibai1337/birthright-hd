import type { Scenario } from './schema';

type Spell = Scenario['spells'][number];
// Factual PC help catalogue (§§016/231); costs whose base is variable are quoted at runtime.
const provenance = {
  status: 'VERIFIED_ORIGINAL' as const,
  source: 'CD RULES.TXT §§016/231/159; historical ACTNMENU.CPP',
  note: 'PC help governs conflicts. Variable costs are described in GAMEPLAY_SYSTEMS.md; effects are independent HD implementations.',
};
function spell(
  id: string,
  name: string,
  item: number,
  holding: 'source' | 'temple',
  minLevel: number,
  casterLevel: number,
  gold: number,
  regency: number,
  effect: Spell['effect'],
  duration = 1,
  unavailableReason?: string,
): Spell {
  return {
    id,
    name,
    originalItemId: item,
    holding,
    minLevel,
    casterLevel,
    gold,
    regency,
    effect,
    duration,
    implemented: !unavailableReason,
    ...(unavailableReason ? { unavailableReason } : {}),
    provenance,
  };
}
